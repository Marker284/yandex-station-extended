#!/bin/sh
# Проверено: Fiero Hi (Станция Лайт, blackthorn), прошивка 0.369.1.50.*. Откат — README.md рядом.
# Голосом в SoundCloud (по образцу voice-spotify.sh из station2-media):
#   «Алиса, включи <что-то> на саундклауде», «Алиса, саундклауд <что-то>» — поиск и запуск;
#   «пауза», «стоп», «выключи» — пауза; «продолжи» — с того же места (в течение часа);
#   «дальше», «следующий» / «предыдущий», «назад» — треки; «сначала» — трек с начала;
#   «перемотай вперёд на 30 секунд», «назад на минуту» — перемотка (без числа — 10 с);
#   «громче», «тише», «громкость 5» (0–10, как у Алисы) — пока играет SoundCloud.
# Команды управления работают, только пока играет SoundCloud.
# В лог попадают только команды SoundCloud, остальная речь никуда не пишется.
export PATH=/opt/bin:/opt/sbin:/usr/bin:/bin:/usr/sbin:/sbin
DIR=$(dirname "$0")
LOG=$DIR/voice.log
PLAY=$DIR/sc-play.sh

note() { echo "$(date '+%m-%d %H:%M:%S'): $*" >> "$LOG"; }

playing() { [ -f /tmp/sc-player.pid ] && kill -0 "$(cat /tmp/sc-player.pid)" 2>/dev/null; }

# На паузе не дольше часа — тогда «продолжи» для SoundCloud
paused() { [ -f /tmp/sc.paused ] && [ $(( $(date +%s) - $(cat /tmp/sc.paused) )) -lt 3600 ]; }

# Числа словами -> цифрами: распознавание пишет то «5», то «пять»
digits() {
    echo " $1 " | sed -E '
        s/ (двадцать|тридцать|сорок|пятьдесят) (один|одну|два|две|три|четыре|пять|шесть|семь|восемь|девять) / \1_\2 /g
        s/ (одну|одна|один) / 1 /g; s/ (две|два) / 2 /g; s/ три / 3 /g; s/ четыре / 4 /g
        s/ пять / 5 /g; s/ шесть / 6 /g; s/ семь / 7 /g; s/ восемь / 8 /g; s/ девять / 9 /g
        s/ десять / 10 /g; s/ пятнадцать / 15 /g; s/ двадцать / 20 /g; s/ тридцать / 30 /g
        s/ сорок / 40 /g; s/ пятьдесят / 50 /g; s/ шестьдесят / 60 /g; s/ девяносто / 90 /g; s/ сто / 100 /g
        s/ двадцать_/ 2_/g; s/ тридцать_/ 3_/g; s/ сорок_/ 4_/g; s/ пятьдесят_/ 5_/g
        s/_(один|одну)/1/g; s/_(два|две)/2/g; s/_три/3/g; s/_четыре/4/g; s/_пять/5/g
        s/_шесть/6/g; s/_семь/7/g; s/_восемь/8/g; s/_девять/9/g'
}

# Секунды перемотки из фразы: «30 секунд», «2 минуты», «минуту», «полминуты»; без числа — 10
seek_seconds() {
    set -- "$(digits "$1")"
    n=$(echo "$1" | sed -n 's/.*[^0-9]\([0-9][0-9]*\) *минут.*/\1/p')
    [ -n "$n" ] && { echo $((n * 60)); return; }
    n=$(echo "$1" | sed -n 's/.*[^0-9]\([0-9][0-9]*\) *сек.*/\1/p')
    [ -n "$n" ] && { echo "$n"; return; }
    case "$1" in
        *полминут*) echo 30 ;;
        *минут*) echo 60 ;;
        *) echo 10 ;;
    esac
}

# «громкость 5» -> 50%, «громкость 40 процентов» -> 40%
volume_level() {
    set -- "$(digits "$1")"
    n=$(echo "$1" | sed -n 's/.*[^0-9]\([0-9][0-9]*\).*/\1/p')
    [ -n "$n" ] || return 1
    case "$1" in *процент*) echo "$n" ;; *) [ "$n" -le 10 ] && echo $((n * 10)) || echo "$n" ;; esac
}

# Запрос из фразы: убираем слово «саундклауд» с предлогом и глагол в начале
query() {
    echo "$1" | sed -E '
        s/(на|в|из|с) (саундклауд[а-я]*|саунд клауд[а-я]*|soundcloud[а-я]*)//I
        s/(саундклауд[а-я]*|саунд клауд[а-я]*|soundcloud)//I
        s/^ *(Алиса,? *)?//I
        s/^ *(Поставь|поставь|Включи|включи|Играй|играй|Найди|найди|Запусти|запусти) *//
        s/ пожалуйста//I
        s/^ +//; s/ +$//'
}

handle() {
    t=$1
    case "$t" in
        *аундклауд*|*аунд\ клауд*|*oundcloud*|*OUNDCLOUD*)
            q=$(query "$t")
            [ -z "$q" ] && q="популярное"
            note "play: $q"
            "$PLAY" play "$q" >> "$LOG" 2>&1 &
            return ;;
    esac
    if ! playing; then
        case "$t" in
            *родолж*|*грай\ дальше*|*ключи\ обратно*) paused && { note "resume ($t)"; "$PLAY" resume >> "$LOG" 2>&1; } ;;
        esac
        return
    fi
    case "$t" in
        *еремота*|*перед\ на\ *|*вперёд\ на\ *|*азад\ на\ *)
            s=$(seek_seconds "$t")
            case "$t" in *азад*) s=-$s ;; esac
            note "seek $s ($t)"; "$PLAY" seek "$s" >> "$LOG" 2>&1 ;;
        *ыключи*|*стоп*|*Стоп*|*хватит*|*Хватит*|*ауза*|*аузу*) note "pause ($t)"; "$PLAY" pause >> "$LOG" 2>&1 ;;
        *начала*|*аново*) note "seek 0 ($t)"; "$PLAY" seek 0 >> "$LOG" 2>&1 ;;
        *ледующ*|*альше*) note "next ($t)"; "$PLAY" next ;;
        *редыдущ*|*азад*) note "prev ($t)"; "$PLAY" prev ;;
        # пока играет SoundCloud, медиа-демон Алисы погашен — громкость держит sc-play.sh
        *ромкост*) v=$(volume_level "$t") && { note "volume $v ($t)"; "$PLAY" volume "$v" >> "$LOG" 2>&1; } ;;
        *ромче*) note "volume +10 ($t)"; "$PLAY" volume +10 >> "$LOG" 2>&1 ;;
        *тише*|*Тише*) note "volume -10 ($t)"; "$PLAY" volume -10 >> "$LOG" 2>&1 ;;
    esac
}

[ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 1000000 ] && : > "$LOG"
note "слушатель запущен"
"$DIR/alice-text.sh" | while IFS= read -r line; do
    # Пока Алиса слушает (1), музыку SoundCloud тише — громкость держит sc-play.sh
    case "$line" in
        "@state 1") playing && touch /tmp/sc.duck; continue ;;
        "@state 0") rm -f /tmp/sc.duck; continue ;;
        "@state "*) continue ;;
    esac
    handle "$(printf '%b' "$line")"
done
